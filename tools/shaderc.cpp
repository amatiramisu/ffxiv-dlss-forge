// Compiles HLSL shaders to DXBC with the d3dcompiler_47.dll next to this program and writes them as a
// C++ header. Runs under Wine/Proton from build_shaders.sh; errors go to <output>.log.
//   shaderc.exe <input.hlsl> <output.h> <array:entry:DEFINE[:profile]>...   (profile defaults to cs_5_0)
#include <windows.h>
#include <d3dcompiler.h>
#include <cstdio>
#include <cstring>
#include <string>
#include <vector>

int main(int argc, char **argv)
{
	if (argc < 4)
		return 2;
	const std::string out_path = argv[2];
	FILE *log = fopen((out_path + ".log").c_str(), "w");
	auto say = [&](const char *fmt, const char *a, const char *b) {
		if (log != nullptr)
		{
			fprintf(log, fmt, a, b);
			fflush(log);
		}
	};

	wchar_t dir[MAX_PATH] = {};
	GetModuleFileNameW(nullptr, dir, MAX_PATH);
	wcscpy(wcsrchr(dir, L'\\') + 1, L"d3dcompiler_47.dll");
	HMODULE compiler = LoadLibraryW(dir);
	const auto compile = compiler != nullptr ? reinterpret_cast<pD3DCompile>(GetProcAddress(compiler, "D3DCompile")) : nullptr;
	if (compile == nullptr || std::memcmp(reinterpret_cast<const char *>(compiler) + 0x40, "Wine builtin DLL", 16) == 0)
	{
		say("%s%s\n", "Microsoft's d3dcompiler_47.dll is required next to shaderc.exe", "");
		return 3;
	}

	FILE *in = fopen(argv[1], "rb");
	if (in == nullptr)
	{
		say("cannot read %s%s\n", argv[1], "");
		return 4;
	}
	std::string src;
	char buf[4096];
	for (size_t n; (n = fread(buf, 1, sizeof(buf), in)) > 0;)
		src.append(buf, n);
	fclose(in);

	std::string name = argv[1];
	const size_t slash = name.find_last_of("\\/");
	if (slash != std::string::npos)
		name = name.substr(slash + 1);
	std::string header = "// Generated by build_shaders.sh from " + name + " with Microsoft's d3dcompiler_47. Do not edit.\n#pragma once\n\n";
	for (int i = 3; i < argc; ++i)
	{
		std::string spec = argv[i];
		const size_t a = spec.find(':'), b = spec.find(':', a + 1);
		if (a == std::string::npos || b == std::string::npos)
			return 5;
		const size_t c = spec.find(':', b + 1);
		const std::string array = spec.substr(0, a), entry = spec.substr(a + 1, b - a - 1);
		const std::string define = spec.substr(b + 1, c == std::string::npos ? std::string::npos : c - b - 1);
		const std::string profile = c == std::string::npos ? "cs_5_0" : spec.substr(c + 1);
		const D3D_SHADER_MACRO defines[] = { { define.c_str(), "1" }, { nullptr, nullptr } };
		ID3DBlob *code = nullptr, *errors = nullptr;
		const HRESULT hr = compile(src.data(), src.size(), name.c_str(), defines, nullptr, entry.c_str(), profile.c_str(), D3DCOMPILE_OPTIMIZATION_LEVEL3, 0, &code, &errors);
		if (errors != nullptr)
		{
			say("%s: %s\n", entry.c_str(), static_cast<const char *>(errors->GetBufferPointer()));
			errors->Release();
		}
		if (FAILED(hr) || code == nullptr)
			return 6;
		const auto *bytes = static_cast<const unsigned char *>(code->GetBufferPointer());
		header += "static const unsigned char " + array + "[] = {";
		for (size_t k = 0; k < code->GetBufferSize(); ++k)
		{
			char hex[8];
			snprintf(hex, sizeof(hex), "%s0x%02x,", k % 16 == 0 ? "\n\t" : " ", bytes[k]);
			header += hex;
		}
		header += "\n};\n\n";
		say("%s: ok%s\n", entry.c_str(), "");
		code->Release();
	}
	FILE *out = fopen(out_path.c_str(), "wb");
	if (out == nullptr)
		return 7;
	fwrite(header.data(), 1, header.size(), out);
	fclose(out);
	return 0;
}
